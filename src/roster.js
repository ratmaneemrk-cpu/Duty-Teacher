export const ROSTER_NAMES = Object.values(WEEKLY).flat()

/** ครูเวรตามตารางประจำสัปดาห์ของวันที่ (YYYY-MM-DD) — วันเสาร์/อาทิตย์ไม่มีเวร */
export function rosterTeachers(date) {
  const names = WEEKLY[parseDateStr(date).getDay()] ?? []
  return names.map((name, i) => ({ uid: '', name, head: i === 0 }))
}

/**
 * ตารางเวรของแต่ละวัน: ถ้าผู้ดูแลจัดเวรเฉพาะวันไว้ (เอกสารใน schedules) ใช้อันนั้น
 * ไม่เช่นนั้นใช้ตารางประจำสัปดาห์
 */
export function scheduleFor(date, overrides) {
  if (overrides[date]) return { ...overrides[date], override: true }
  return { date, teachers: rosterTeachers(date), note: '', override: false }
}
